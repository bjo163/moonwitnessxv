export function modelViewCopy(locale: Locale): LocaleCatalog<keyof typeof catalog.en>['en'] {
  return catalog[locale]
}

export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{([a-zA-Z]+)\}/g, (match, key: string) => String(values[key] ?? match))
}

export function editorStatusMessage(locale: Locale, status: unknown): string | null {
  if (status !== 'created' && status !== 'updated' && status !== 'deleted') return null
  return modelViewCopy(locale)[status]
}

export function editorFailureMessage(locale: Locale, code: unknown): string | null {
  const keys = {
    invalid: 'errorInvalid',
    unauthorized: 'errorUnauthorized',
    expired: 'errorExpired',
    unavailable: 'errorUnavailable',
    not_found: 'errorNotFound',
    unconfirmed: 'errorUnconfirmed',
  } as const
  if (typeof code !== 'string' || code.length === 0) return null
  return Object.hasOwn(keys, code)
    ? modelViewCopy(locale)[keys[code as keyof typeof keys]]
    : modelViewCopy(locale).errorGeneric
}
