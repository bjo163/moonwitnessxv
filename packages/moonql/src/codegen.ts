import type { FieldMeta, JsonSchema, SchemaDocument } from '@moonwitness/core'

/**
 * Registry metadata -> TypeScript SDK source. Pure string work, zero deps and
 * zero I/O so `pnpm gen:sdk` can run without an engine, a database or a socket.
 * Output is deterministic: registry iteration order, no timestamps.
 */

type Json = Record<string, unknown>

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/

const quote = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/** `ops_audit` -> `OpsAudit`, `stationCatalog` -> `StationCatalog` */
export function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

const propKey = (key: string): string => (IDENT_RE.test(key) ? key : quote(key))

const paren = (type: string): string => (type.includes(' | ') ? `(${type})` : type)

/** literal rendering for the ENDPOINTS table */
function lit(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return `[${value.map(lit).join(', ')}]`
  if (typeof value === 'string') return quote(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  return 'null'
}

/** JSON Schema -> TS type expression (union-first, depth-capped to stay finite) */
export function tsType(schema: JsonSchema | undefined, depth = 0): string {
  if (!schema || depth > 4) return 'unknown'
  const s = schema as Json

  if (Array.isArray(s.enum)) {
    return (s.enum as unknown[]).map((v) => (typeof v === 'string' ? quote(v) : lit(v))).join(' | ')
  }

  const type = s.type
  if (Array.isArray(type)) {
    return (type as string[]).map((t) => tsType({ ...s, type: t }, depth)).join(' | ')
  }

  switch (type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `${paren(tsType(s.items as Json | undefined, depth + 1))}[]`
    case 'object': {
      const properties = (s.properties ?? {}) as Record<string, Json>
      const required = new Set((s.required as string[] | undefined) ?? [])
      const parts = Object.entries(properties).map(
        ([key, value]) => `${propKey(key)}${required.has(key) ? '' : '?'}: ${tsType(value, depth + 1)}`,
      )
      return parts.length ? `{ ${parts.join('; ')} }` : 'Record<string, unknown>'
    }
    default:
      return 'unknown'
  }
}

interface RowSpec {
  readSchema: JsonSchema
  fields: Record<string, FieldMeta>
  /** view: only these m2o keys are really in the output */
  expand?: string[]
}

/** property lines of a row interface (relations keep their named model interface) */
function rowBody(spec: RowSpec): string {
  const schema = spec.readSchema as Json
  const properties = (schema.properties ?? {}) as Record<string, Json>
  const required = new Set((schema.required as string[] | undefined) ?? [])
  const expanded = spec.expand ? new Set(spec.expand) : undefined
  const lines: string[] = []

  for (const [key, value] of Object.entries(properties)) {
    if (key.endsWith('Record')) {
      const relation = spec.fields[key.slice(0, -6)]?.relation
      if (relation) {
        const base = key.slice(0, -6)
        if (expanded && !expanded.has(base)) continue
        lines.push(`  ${propKey(key)}?: ${pascal(relation.model)}Row | null`)
        continue
      }
    }
    lines.push(`  ${propKey(key)}${required.has(key) ? '' : '?'}: ${tsType(value)}`)
  }
  return lines.length ? `\n${lines.join('\n')}\n` : ''
}

const iface = (name: string, body: string): string => `export interface ${name} {${body}}`

/** model create/update payloads: required keys stay required, the rest optional */
function writeBody(schema: JsonSchema): string {
  const s = schema as Json
  const properties = (s.properties ?? {}) as Record<string, Json>
  const required = new Set((s.required as string[] | undefined) ?? [])
  const lines = Object.entries(properties).map(
    ([key, value]) => `  ${propKey(key)}${required.has(key) ? '' : '?'}: ${tsType(value)}`,
  )
  return lines.length ? `\n${lines.join('\n')}\n` : ''
}

export function generateClientSource(doc: SchemaDocument): string {
  const modelNames = Object.keys(doc.models)
  const viewNames = Object.keys(doc.views)
  const chunks: string[] = []

  chunks.push('// AUTO-GENERATED by `pnpm gen:sdk` — do not edit by hand.')
  chunks.push('// Source of truth: the moonql registry (models, views, endpoints).')
  chunks.push('')
  chunks.push(`export type ModelName = ${modelNames.length ? modelNames.map(quote).join(' | ') : 'never'}`)
  chunks.push(`export type ViewName = ${viewNames.length ? viewNames.map(quote).join(' | ') : 'never'}`)
  chunks.push('')

  for (const name of modelNames) {
    const meta = doc.models[name]!
    chunks.push(iface(`${pascal(name)}Row`, rowBody({ readSchema: meta.readSchema, fields: meta.fields })))
    chunks.push(iface(`${pascal(name)}Create`, writeBody(meta.createSchema)))
    chunks.push(iface(`${pascal(name)}Update`, writeBody(meta.updateSchema)))
    chunks.push('')
  }

  for (const key of viewNames) {
    const meta = doc.views[key]!
    const source = doc.models[meta.from]?.fields ?? {}
    chunks.push(iface(`${pascal(key)}Output`, rowBody({ readSchema: meta.readSchema, fields: source, expand: meta.expand ?? [] })))
    chunks.push('')
  }

  const mapBody = (suffix: string): string =>
    modelNames.length ? `\n${modelNames.map((n) => `  ${propKey(n)}: ${pascal(n)}${suffix}`).join('\n')}\n` : ''
  chunks.push(iface('Rows', mapBody('Row')))
  chunks.push(iface('Creates', mapBody('Create')))
  chunks.push(iface('Updates', mapBody('Update')))
  chunks.push(
    iface(
      'ViewOutputs',
      viewNames.length ? `\n${viewNames.map((v) => `  ${propKey(v)}: ${pascal(v)}Output`).join('\n')}\n` : '',
    ),
  )
  chunks.push('')

  chunks.push(
    `export const MODEL_NAMES = [${modelNames.map(quote).join(', ')}] as const satisfies readonly ModelName[]`,
  )
  chunks.push(`export const VIEW_NAMES = [${viewNames.map(quote).join(', ')}] as const satisfies readonly ViewName[]`)
  chunks.push(
    `export const ENDPOINTS = [${doc.endpoints
      .map((e) => `{ method: ${quote(e.method)}, path: ${quote(e.path)}, acl: ${lit(e.acl)}, stream: ${e.stream === true} }`)
      .join(', ')}] as const`,
  )
  // The digest travels with the generated client so a running client can compare it
  // against the server's own answer and say "I was built against a different hub".
  // Only the digest is baked in: the hub's advertised apiVersion comes from runtime
  // config, and committing an env-derived string would make this file drift in CI.
  chunks.push(`export const SCHEMA_HASH: string = ${quote(doc.schemaHash)}`)
  chunks.push('')

  return chunks.join('\n')
}
