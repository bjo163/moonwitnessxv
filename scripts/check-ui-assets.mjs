#!/usr/bin/env node
/**
 * scripts/check-ui-assets.mjs
 *
 * UI-F14 icon/vector pipeline gate + QA-01 source/license ledger enforcer.
 *
 * Enforces, over the assets that the applications actually serve:
 *   1. Accessible naming — every shipped .svg carries `<title>`, or
 *      `role="img"` + `aria-label`, or is explicitly decorative
 *      (`aria-hidden="true"`).
 *   2. Self-containment — no `<script>`, no remote `href`/`xlink:href`,
 *      no `@import`, no remote `<image>`, no unaccounted base64/font payload.
 *   3. Ledger integrity — every discovered asset has a row in
 *      docs/audit/ui-asset-ledger-d54ad43.md with author, origin, SPDX/license,
 *      consent, usage status and SHA-256. A missing row, an unresolved rights
 *      status, or a hash mismatch is a violation. Stale rows (ledger without a
 *      file) are violations too.
 *   4. Reference containment — nothing under `apps/**` may point at the
 *      reference-only `docs/design/mockups-xv` media (ADR-0009 section 2.1).
 *
 * Scan universe (what is deliberately NOT scanned, and why):
 *   IN  — the public dirs the apps serve and that are git-tracked sources:
 *         apps/dock/public, apps/headquarters/public, apps/cockpit/public,
 *         apps/cockpit/client/public (Vite `publicDir`, since vite `root` is
 *         apps/cockpit/client).
 *   OUT — `dist/`, `.next/`, `build/`: generated by the app build from the
 *         sources above; auditing them would double-count and would let a
 *         stale bundle mask a source drift.
 *   OUT — `docs/design/mockups-xv/**`: reference-only per ADR-0009. They are
 *         not production assets, so they get no ledger row; instead check 4
 *         proves no app can reach them.
 *   OUT — `packages/moonui` crown/seal/icons: inline JSX is source code, not a
 *         served binary asset; it ships inside JS bundles and is covered by the
 *         app test suites plus `pnpm ui:check`.
 *
 * Exit 0 when clean, 1 on any violation. No third-party dependencies.
 */

import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------
const argv = process.argv.slice(2)
function flagValue(name, fallback) {
  const i = argv.indexOf(`--${name}`)
  return i !== -1 && argv[i + 1] ? resolve(argv[i + 1]) : fallback
}

const ROOT = flagValue('root', resolve(fileURLToPath(import.meta.url), '..', '..'))
const LEDGER_PATH = flagValue('ledger', join(ROOT, 'docs/audit/ui-asset-ledger-d54ad43.md'))
const LEDGER_REL = toPosix(relative(ROOT, LEDGER_PATH))

// ANSI helpers (mirrors scripts/check-ui-consistency.mjs)
const cyan = (s) => `\x1b[36m${s}\x1b[0m`
const bold = (s) => `\x1b[1m${s}\x1b[0m`
const green = (s) => `\x1b[32m${s}\x1b[0m`
const yellow = (s) => `\x1b[33m${s}\x1b[0m`
const red = (s) => `\x1b[31m${s}\x1b[0m`
const magenta = (s) => `\x1b[35m${s}\x1b[0m`
const gray = (s) => `\x1b[90m${s}\x1b[0m`

/** Public dirs actually served by an app. Add a dir here when an app gains one. */
const ASSET_DIRS = [
  'apps/dock/public',
  'apps/headquarters/public',
  'apps/cockpit/public',
  'apps/cockpit/client/public',
]

/** Build output / vendor dirs never treated as source assets. */
const SKIP_DIRS = new Set(['node_modules', '.next', 'dist', 'build', '.git', 'coverage', '.turbo'])

/** Binary + vector media the pipeline accounts for. */
const ASSET_EXTENSIONS = new Set([
  '.svg', '.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif', '.ico',
  '.mp3', '.ogg', '.wav', '.m4a', '.aac', '.flac',
  '.mp4', '.webm',
  '.woff', '.woff2', '.ttf', '.otf', '.eot',
])

/** Ledger statuses that are allowed to exist in a served directory. */
const SHIPPING_STATUS = 'CLEARED'
/** Source files scanned for references to the reference-only mockup media. */
const CODE_EXTENSIONS = new Set(['.tsx', '.ts', '.js', '.mjs', '.cjs', '.css', '.html', '.json', '.md', '.txt'])

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
const violations = []
function fail(check, message, hint) {
  violations.push({ check, message, hint })
  console.log(`  ${red('\u2716 FAIL')}: ${bold(message)}`)
  if (hint) console.log(`    ${yellow('Fix:')} ${hint}`)
}

function toPosix(p) {
  return p.split(sep).join('/')
}

function sha256(absPath) {
  return createHash('sha256').update(readFileSync(absPath)).digest('hex')
}

function walkAssets(dir, acc) {
  const full = resolve(ROOT, dir)
  if (!existsSync(full)) return acc
  for (const entry of readdirSync(full)) {
    if (SKIP_DIRS.has(entry)) continue
    const p = join(full, entry)
    const st = statSync(p)
    if (st.isDirectory()) walkAssets(toPosix(relative(ROOT, p)), acc)
    else if (ASSET_EXTENSIONS.has(entry.slice(entry.lastIndexOf('.')).toLowerCase())) {
      acc.add(toPosix(relative(ROOT, p)))
    }
  }
  return acc
}

function walkAll(dir, acc) {
  const full = resolve(ROOT, dir)
  if (!existsSync(full)) return acc
  let st
  try { st = statSync(full) } catch { return acc }
  if (!st.isDirectory()) return acc
  for (const entry of readdirSync(full)) {
    if (SKIP_DIRS.has(entry)) continue
    const p = join(full, entry)
    const childStat = statSync(p)
    if (childStat.isDirectory()) walkAll(toPosix(relative(ROOT, p)), acc)
    else acc.add(toPosix(relative(ROOT, p)))
  }
  return acc
}

/**
 * Ledger = markdown table in docs/audit/ui-asset-ledger-<sha>.md.
 * Header columns are matched by name so the table may be reordered.
 */
function parseLedger() {
  if (!existsSync(LEDGER_PATH)) {
    fail('ledger', `Ledger file not found: ${LEDGER_REL}`, 'Regenerate the asset ledger for the current baseline.')
    return { rows: new Map(), required: [] }
  }
  const lines = readFileSync(LEDGER_PATH, 'utf8').split(/\r?\n/)
  const rows = new Map()
  let required = []
  let header = null
  for (const line of lines) {
    const trimmed = line.trim()
    const isRow = trimmed.startsWith('|') && trimmed.endsWith('|')
    if (!isRow) { header = null; continue }
    const cells = trimmed.slice(1, -1).split('|').map((c) => c.trim())
    if (cells.every((c) => /^:?-{2,}:?$/.test(c))) continue // separator
    if (cells.some((c) => c.toLowerCase().includes('asset path'))) {
      header = cells.map((c) => c.toLowerCase())
      required = ['asset path', 'sha-256', 'author / origin', 'license (spdx)', 'consent', 'status']
        .filter((k) => header.some((h) => h.includes(k)))
      continue
    }
    if (!header) continue
    const rec = {}
    header.forEach((h, i) => { rec[h] = cells[i] ?? '' })
    const pathCell = rec[header.find((h) => h.includes('asset path'))] ?? ''
    const assetPath = pathCell.replace(/`/g, '')
    if (!assetPath || !assetPath.includes('/')) continue
    rows.set(assetPath, rec)
  }
  if (rows.size === 0) {
    fail('ledger', `Ledger ${LEDGER_REL} contains no parseable asset rows`, 'Add an "Asset path" table with one row per served asset.')
  }
  return { rows, required }
}

// ---------------------------------------------------------------------------
// Banner
// ---------------------------------------------------------------------------
console.log(bold(cyan('\u2550'.repeat(71))))
console.log(bold(cyan('   MOONWITNESS UI ASSET PIPELINE  \u2014  vector a11y + source/license ledger')))
console.log(bold(cyan('\u2550'.repeat(71))))
console.log(gray(`Root: ${ROOT}`))
console.log(gray(`Ledger: ${LEDGER_REL}`))
console.log(gray(`Scanned dirs: ${ASSET_DIRS.join(', ')}\n`))

// ---------------------------------------------------------------------------
// Discovery
// ---------------------------------------------------------------------------
const discovered = new Set()
for (const dir of ASSET_DIRS) walkAssets(dir, discovered)
const sortedAssets = [...discovered].sort()

const svgs = sortedAssets.filter((a) => a.toLowerCase().endsWith('.svg'))
const rasters = sortedAssets.filter((a) => /\.(png|jpe?g|webp|gif|avif|ico)$/i.test(a))
const media = sortedAssets.filter((a) => /\.(mp3|ogg|wav|m4a|aac|flac|mp4|webm)$/i.test(a))
const fonts = sortedAssets.filter((a) => /\.(woff2?|ttf|otf|eot)$/i.test(a))

// ---------------------------------------------------------------------------
// CHECK 1: SVG accessible name
// ---------------------------------------------------------------------------
console.log(bold(magenta('\u25C6 CHECK 1: SVG accessible name (title / role+aria-label / decorative)')))
let svgNamed = 0
for (const rel of svgs) {
  const content = readFileSync(resolve(ROOT, rel), 'utf8')
  const hasTitle = /<title(?:\s|>)[\s\S]*?<\/title\s*>/i.test(content)
  const hasLabel = /aria-label\s*=\s*"[^"]+"/i.test(content)
  const hasRoleImg = /role\s*=\s*"img"/i.test(content)
  const decorative = /aria-hidden\s*=\s*"true"/i.test(content)
  if (hasTitle || (hasRoleImg && hasLabel) || decorative) {
    svgNamed++
    const how = hasTitle ? '<title>' : hasRoleImg && hasLabel ? 'role="img"+aria-label' : 'aria-hidden="true"'
    console.log(`  ${green('\u2714 PASS')}: ${rel} ${gray(`(${how})`)}`)
  } else {
    fail('svg-accessible-name', `${rel} has no accessible name`,
      'Add <title>…</title>, or role="img" with aria-label, or aria-hidden="true" when purely decorative.')
  }
}
if (svgs.length === 0) console.log(`  ${yellow('\u26A0 NONE')}: no shipped .svg files found in the scanned dirs.`)

// ---------------------------------------------------------------------------
// CHECK 2: SVG self-containment
// ---------------------------------------------------------------------------
console.log(`\n${bold(magenta('\u25C6 CHECK 2: SVG self-containment (no script / remote ref / @import / payload)'))}`)
let svgSafe = 0
for (const rel of svgs) {
  const content = readFileSync(resolve(ROOT, rel), 'utf8')
  let clean = true
  const report = (why) => { fail('svg-self-contained', `${rel}: ${why}`, 'Inline the asset or drop the remote reference.') ; clean = false }

  if (/<script/i.test(content)) report('contains <script>')
  if (/@import/i.test(content)) report('contains @import')
  const refs = content.match(/(?:xlink:href|href)\s*=\s*"([^"]*)"/gi) ?? []
  for (const ref of refs) {
    const url = ref.replace(/^.*?=\s*"/, '').replace(/"$/, '')
    if (/^(https?:)?\/\//i.test(url) || /^mailto:/i.test(url)) report(`remote reference: ${url}`)
  }
  if (/<image[^>]*(?:xlink:)?href\s*=\s*"(?:https?:)?\/\//i.test(content)) report('remote <image> resource')
  const dataUris = content.match(/data:[^;"\s]+;base64,/gi) ?? []
  if (dataUris.length) report(`${dataUris.length} base64 payload(s) that the pipeline cannot account for`)
  const fontRefs = content.match(/url\(\s*["']?(?:https?:)?\/\//gi) ?? []
  if (fontRefs.length) report(`${fontRefs.length} external url() reference(s)`)

  if (clean) {
    svgSafe++
    console.log(`  ${green('\u2714 PASS')}: ${rel} is self-contained`)
  }
}

// ---------------------------------------------------------------------------
// CHECK 3: ledger integrity + rights resolution
// ---------------------------------------------------------------------------
console.log(`\n${bold(magenta('\u25C6 CHECK 3: ledger row + content hash + resolved rights for every served asset'))}`)
const { rows: ledger } = parseLedger()
let ledgerMatched = 0
const ledgerBlockers = []

for (const rel of sortedAssets) {
  const row = ledger.get(rel)
  if (!row) {
    fail('ledger-row-missing', `${rel} is served but has no ledger row`,
      `Add a row to ${LEDGER_REL} recording author, origin, SPDX/license, consent and SHA-256.`)
    continue
  }
  const expected = (row['sha-256'] ?? row['sha256'] ?? '').replace(/`/g, '').trim()
  const actual = sha256(resolve(ROOT, rel))
  const status = (row['status'] ?? '').toUpperCase()

  if (expected !== actual) {
    fail('ledger-hash-mismatch', `${rel} content hash does not match the ledger`,
      `ledger: ${expected || '(blank)'}  actual: ${actual} — update the ledger only after a rights review.`)
    continue
  }
  if (!status.includes(SHIPPING_STATUS)) {
    ledgerBlockers.push({ rel, status, license: row['license (spdx)'] ?? row['license'] ?? '' })
    fail('rights-unresolved', `${rel} is served with ledger status "${status || '(blank)'}"`,
      'Only CLEARED assets may live in a served public dir. Obtain rights evidence, or remove the file from production.')
    continue
  }
  const license = (row['license (spdx)'] ?? row['license'] ?? '').trim()
  const consent = (row['consent'] ?? '').trim()
  const author = (Object.entries(row).find(([k]) => k.includes('author'))?.[1] ?? '').trim()
  if (!license || /^(-|none|unknown)$/i.test(license)) {
    fail('ledger-field-incomplete', `${rel} has an empty License (SPDX) field`, 'Fill the field or mark the row UNRESOLVED.')
    continue
  }
  if (!author || author.toUpperCase().startsWith('UNRESOLVED')) {
    fail('ledger-field-incomplete', `${rel} has no recorded author/origin`, 'Fill the field or mark the row UNRESOLVED.')
    continue
  }
  if (!consent) {
    fail('ledger-field-incomplete', `${rel} has no Consent entry`, 'State "not applicable" or record the depicted person\'s consent.')
    continue
  }
  ledgerMatched++
  console.log(`  ${green('\u2714 CLEARED')}: ${rel} ${gray(`(${license})`)}`)
}

// A CLEARED row whose file is gone is a stale claim; a row that declares a
// non-shipping status (UNRESOLVED / EXCLUDED / REFERENCE-ONLY / PLANNED /
// BUILD-ARTIFACT / CODE-NOT-ASSET) may legitimately point at nothing, because
// keeping that evidence after removal is the whole point of the ledger.
for (const [rel, row] of ledger) {
  if (discovered.has(rel)) continue
  const st = (row['status'] ?? '').toUpperCase()
  if (st.includes(SHIPPING_STATUS)) {
    fail('ledger-stale-row', `${rel} is ledgered as ${SHIPPING_STATUS} but no file exists in any scanned dir`,
      'Remove the row, restore the asset, or restate the row with a non-shipping status.')
  }
}

// ---------------------------------------------------------------------------
// CHECK 4: no app references the reference-only mockup media
// ---------------------------------------------------------------------------
console.log(`\n${bold(magenta('\u25C6 CHECK 4: ADR-0009 containment \u2014 apps/** must not reach docs/design/mockups-xv media'))}`)
const REF_PATTERNS = [/mockups-xv\/png/i, /mockups-xv\/[0-9]{2}_[a-z_]+\.svg/i, /docs\/design\/mockups-xv/i]
const appFiles = [...walkAll('apps', new Set())]
let refHits = 0
for (const rel of appFiles) {
  const ext = rel.slice(rel.lastIndexOf('.'))
  if (!CODE_EXTENSIONS.has(ext.toLowerCase())) continue
  let content
  try { content = readFileSync(resolve(ROOT, rel), 'utf8') } catch { continue }
  const lines = content.split(/\r?\n/)
  lines.forEach((line, i) => {
    // first matching pattern only, so one offending line is one violation
    const hit = REF_PATTERNS.find((p) => p.test(line))
    if (!hit) return
    refHits++
    fail('reference-containment', `${rel}:${i + 1} references reference-only mockup media`,
      `Remove the embed: ${line.trim().slice(0, 90)} — ADR-0009 forbids shipping these files.`)
  })
}
if (refHits === 0) {
  console.log(`  ${green('\u2714 PASS')}: ${appFiles.length} files under apps/ contain no mockups-xv media reference.`)
}

// ---------------------------------------------------------------------------
// Non-asset classes (informational, deterministic)
// ---------------------------------------------------------------------------
console.log(`\n${bold(magenta('\u25C6 INFO: asset classes the pipeline accounts for'))}`)
console.log(`  ${gray('inline JSX artwork (packages/moonui: Crown, StationSeal, icons/*) = source code, not binary assets; never ledgered, covered by app tests + pnpm ui:check.')}`)
const refDir = join(ROOT, 'docs/design/mockups-xv')
const refPng = existsSync(join(refDir, 'png')) ? readdirSync(join(refDir, 'png')).filter((f) => f.endsWith('.png')).length : 0
const refSvg = existsSync(refDir) ? readdirSync(refDir).filter((f) => f.endsWith('.svg')).length : 0
console.log(`  ${gray(`docs/design/mockups-xv/** = ${refPng} PNG + ${refSvg} SVG reference-only, excluded from the scan universe by ADR-0009.`)}`)
console.log(`  ${gray('build output (dist/, .next/) = derived copies, excluded; verify against source, not bundle.')}`)

// ---------------------------------------------------------------------------
// Summary + exit
// ---------------------------------------------------------------------------
const byCheck = {}
for (const v of violations) byCheck[v.check] = (byCheck[v.check] ?? 0) + 1
const counts = (k) => byCheck[k] ?? 0

console.log(`\n${bold(cyan('\u2550'.repeat(71)))}`)
console.log(
  `Assets scanned: ${bold(String(sortedAssets.length))}` +
  ` | SVG: ${svgs.length} | raster: ${rasters.length} | audio/video: ${media.length} | font: ${fonts.length}` +
  ` | ledger rows: ${ledger.size}`
)
console.log(
  `Files scanned: ${bold(String(appFiles.length + sortedAssets.length))}` +
  ` | Total Violations: ${violations.length > 0 ? red(String(violations.length)) : green('0')}`
)
console.log(gray('machine-readable summary:'))
console.log(`SUMMARY|assets_total=${sortedAssets.length}|svg_total=${svgs.length}|svg_named=${svgNamed}|svg_selfcontained=${svgSafe}|raster=${rasters.length}|media=${media.length}|font=${fonts.length}|ledger_rows=${ledger.size}|ledger_cleared=${ledgerMatched}|ledger_blockers=${ledgerBlockers.length}|app_files=${appFiles.length}|reference_hits=${refHits}|violations_total=${violations.length}|violations_svg_accessiblename=${counts('svg-accessible-name')}|violations_svg_selfcontained=${counts('svg-self-contained')}|violations_ledger_missing=${counts('ledger-row-missing')}|violations_ledger_hash=${counts('ledger-hash-mismatch')}|violations_rights=${counts('rights-unresolved')}|violations_ledger_field=${counts('ledger-field-incomplete')}|violations_ledger_stale=${counts('ledger-stale-row')}|violations_reference=${counts('reference-containment')}|exit=${violations.length > 0 ? 1 : 0}`)
console.log(bold(cyan('\u2550'.repeat(71))) + '\n')

if (violations.length > 0) {
  console.error(red(bold(`\u274C UI asset pipeline check FAILED with ${violations.length} violation(s).`)))
  if (ledgerBlockers.length) {
    console.error(yellow(`QA-01 blockers: ${ledgerBlockers.length} asset(s) are served with unresolved rights and must be pulled from production or cleared by a rights review.`))
  }
  process.exit(1)
}
console.log(green(bold('\u2728 UI asset pipeline check PASSED: every served asset is named, self-contained, ledgered and rights-cleared.')))
process.exit(0)
